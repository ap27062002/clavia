#!/usr/bin/env node
/**
 * Brings a new version of the Repository prototype into the app.
 *
 *   node repository-import.mjs path/to/Calm.dc.html
 *
 * Reads the Design artifact's .dc.html (the "Repository" artboard of the
 * Clavia Repository Prototype) and writes src/repository-dc.js: its
 * template, its <helmet> CSS and its logic class, which src/dc-mini.js
 * renders. The prototype's own rail is left out — the app has one.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const file = process.argv[2];
if (!file) { console.error('usage: node repository-import.mjs <Calm.dc.html>'); process.exit(1); }
const html = readFileSync(file, 'utf8');

const between = (s, a, b, from = 0) => {
  const i = s.indexOf(a, from);
  if (i < 0) throw new Error('not found: ' + a);
  const j = s.indexOf(b, i + a.length);
  if (j < 0) throw new Error('not found: ' + b);
  return [s.slice(i + a.length, j), i, j + b.length];
};

let [xdc] = between(html, '<x-dc>', '</x-dc>');
const [helmet, h0, h1] = between(xdc, '<helmet>', '</helmet>');
xdc = xdc.slice(0, h0) + xdc.slice(h1);
const css = between(helmet, '<style>', '</style>')[0];

/* the prototype's rail: the app's own rail stands in for it */
const [rail, r0, r1] = between(xdc, '<nav aria-label="Main"', '</nav>');
if (rail.includes('<nav')) throw new Error('the Main nav holds another nav; cut it by hand');
xdc = xdc.slice(0, r0) + xdc.slice(r1);

const script = html.slice(html.indexOf('data-dc-script'));
const logic = script.slice(script.indexOf('>') + 1, script.lastIndexOf('</script>'));
new Function('DCLogic', logic + '\n;return Component;'); // fails loudly on a syntax error

const LS = String.fromCharCode(0x2028), PS = String.fromCharCode(0x2029);
const lit = (s) => JSON.stringify(s).replace(/<\//g, "<\\/").split(LS).join("\\u2028").split(PS).join("\\u2029");
const out = `/* Generated by repository-import.mjs from the Repository prototype — do not edit by hand.
   Imported ${new Date().toISOString().slice(0, 10)}. */
const REPO_DC = {
  template: ${lit(xdc)},
  css: ${lit(css)},
  logic: ${lit(logic)}
};
`;
writeFileSync(join(root, 'src', 'repository-dc.js'), out);
console.log(`src/repository-dc.js  ${(out.length / 1024).toFixed(1)} KB  (template ${(xdc.length / 1024).toFixed(0)} KB, logic ${(logic.length / 1024).toFixed(0)} KB)`);
